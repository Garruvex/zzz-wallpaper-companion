// Explicit, offline cross-repository generation. No running Companion required.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { execFileSync } = require('node:child_process');
const root = path.resolve(__dirname, '..');
const hash = bytes => crypto.createHash('sha256').update(bytes).digest('hex');
const args = process.argv.slice(2);
const check = args.includes('--check');
const at = args.indexOf('--wallpaper');
const wallpaper = at < 0 ? null : path.resolve(args[at + 1] || '');
if ((at >= 0 && (!args[at + 1] || args[at + 1].startsWith('--'))) || args.some((v, i) => v !== '--check' && v !== '--wallpaper' && !(at >= 0 && i === at + 1))) throw new Error('Usage: node tools/generate-contract.cjs [--check] [--wallpaper <checkout>]');
// Git may check JSON out with CRLF on Windows; digest canonical LF bytes.
const bytes = fs.readFileSync(path.join(root, 'api/openapi.json'), 'utf8').replace(/\r\n/g, '\n');
const doc = JSON.parse(bytes);
const digest = hash(bytes);
if (doc.openapi !== '3.0.3') throw new Error('Expected OpenAPI 3.0.3');
const namespaced = /^[A-Za-z][A-Za-z0-9]*(?:\.[A-Za-z][A-Za-z0-9]*)+$/;
for (const name of Object.keys(doc.components?.schemas || {})) if (!namespaced.test(name)) throw new Error(`Schema requires a namespace: ${name}`);
function validateRefs(value) {
  if (!value || typeof value !== 'object') return;
  if (value.$ref && (!value.$ref.startsWith('#/components/schemas/') || !Object.prototype.hasOwnProperty.call(doc.components.schemas, value.$ref.slice('#/components/schemas/'.length)))) throw new Error(`Unresolved/unsupported schema reference: ${value.$ref}`);
  Object.values(value).forEach(validateRefs);
}
validateRefs(doc);
const methods = new Set(['get', 'post', 'put', 'patch', 'delete', 'head', 'options']);
const ids = new Set();
const operations = [];
for (const [route, item] of Object.entries(doc.paths)) {
  for (const [method, value] of Object.entries(item)) {
    if (!methods.has(method)) throw new Error(`Unsupported path item ${route}: ${method}`);
    const id = value.operationId;
    if (!id || ids.has(id)) throw new Error(`Missing/duplicate operation ID ${id}`);
    if (!namespaced.test(id)) throw new Error(`Operation requires a namespace: ${id}`);
    if (!['read', 'explicit', 'disabled'].includes(value['x-explorer-execution'])) throw new Error(`${id}: missing execution policy`);
    if (value['x-response-type'] && !['json', 'binary', 'stream', 'event-stream'].includes(value['x-response-type'])) throw new Error(`${id}: unsupported response type`);
    ids.add(id);
    const parameters = value.parameters || [];
    for (const segment of route.matchAll(/\{([^}]+)\}/g)) {
      if (!parameters.some(p => p.in === 'path' && p.name === segment[1] && p.required)) throw new Error(`${id}: missing required path parameter ${segment[1]}`);
    }
    if (parameters.some(p => !['path', 'query', 'header'].includes(p.in) || p.$ref)) throw new Error(`${id}: unsupported parameter mapping`);
    const contentTypes = Object.keys(value.requestBody?.content || {});
    if (contentTypes.length > 1) throw new Error(`${id}: ambiguous request content type`);
    operations.push({ id, method: method.toUpperCase(), path: route, parameters: parameters.map(p => ({ name: p.name, in: p.in, required: !!p.required })), bodyType: contentTypes[0] || null, bodyRequired: !!value.requestBody?.required, responseType: value['x-response-type'] || 'json', timeout: value['x-client-timeout-ms'] || null, aliasOf: value['x-alias-of'] || null, protocol: value['x-protocol-range'], sideEffects: value['x-side-effects'] || [], execution: value['x-explorer-execution'] });
  }
}
operations.sort((a, b) => a.id < b.id ? -1 : a.id > b.id ? 1 : 0);
for (const op of operations) if (op.aliasOf && !ids.has(op.aliasOf)) throw new Error(`${op.id}: unknown alias ${op.aliasOf}`);
const quote = JSON.stringify;
let go = '// Code generated by tools/generate-contract.cjs; DO NOT EDIT.\npackage api\n\nconst ContractDigest = ' + quote(digest) + '\n\nfunc Operations() []Operation {\n\treturn []Operation{\n';
for (const op of operations) go += `\t\t{ID: ${quote(op.id)}, Method: ${quote(op.method)}, Path: ${quote(op.path)}, AliasOf: ${quote(op.aliasOf || '')}},\n`;
go += '\t}\n}\n';
go = execFileSync('gofmt', { input: go, encoding: 'utf8' });
let js = '// Code generated by Companion tools/generate-contract.cjs; DO NOT EDIT.\n';
js += `export const CONTRACT_DIGEST = ${quote(digest)};\nexport const CONTRACT_VERSION = ${quote(doc.info.version)};\n`;
js += `const table = ${JSON.stringify(Object.fromEntries(operations.map(op => [op.id, op])), null, 2)};\n`;
js += 'function freeze(value) {\n  if (value && typeof value === "object") { Object.values(value).forEach(freeze); Object.freeze(value); }\n  return value;\n}\nexport const operations = freeze(table);\n';
const outputs = [[path.join(root, 'internal/api/operations_generated.go'), go]];
if (wallpaper) {
  const target = path.join(wallpaper, 'script/services/companion/operations.generated.js');
  const pinFile = path.join(wallpaper, 'script/services/companion/contract-pin.json');
  let previous = null;
  if (fs.existsSync(pinFile)) previous = JSON.parse(fs.readFileSync(pinFile, 'utf8'));
  const revision = previous?.contractDigest === digest ? previous.sourceRevision : execFileSync('git', ['rev-parse', 'HEAD'], { cwd: root, encoding: 'utf8' }).trim();
  // The revision must actually contain these contract bytes, including after edits.
  const pinned = execFileSync('git', ['show', `${revision}:api/openapi.json`], { cwd: root });
  if (hash(pinned) !== digest) throw new Error('Commit the canonical contract before pinning wallpaper artifacts');
  const pin = { sourceRepository: 'github.com/Garruvex/zzz-wallpaper-companion', sourceRevision: revision, contractVersion: doc.info.version, contractDigest: digest, operationsDigest: hash(js) };
  outputs.push([target, js], [pinFile, JSON.stringify(pin, null, 2) + '\n']);
}
for (const [filename, content] of outputs) {
  if (check) {
    const current = fs.existsSync(filename) ? fs.readFileSync(filename, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== content) throw new Error(`Generated artifact drift: ${filename}`);
  } else {
    fs.mkdirSync(path.dirname(filename), { recursive: true });
    fs.writeFileSync(filename, content);
  }
}
console.log(`${check ? 'Checked' : 'Generated'} ${operations.length} operations (${digest})${wallpaper ? ' including pinned wallpaper artifacts' : ''}.`);
